const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {fixture, root} = require('./ui_fixture.cjs');
const {snapshot, threads, profileSnapshot} = require('./performance_sample.cjs');
(async () => {
  const requests=[], pending=[], copied=[];
  let failScan=false, delayScan=false, cpu=82.4;
  const scans=[];
  const response=data=>({ok:true,json:async()=>data});
  const f=await fixture({fetch:async (url)=>{
    requests.push(url);
    if(url==='/api/session')return response({token:'test'});
    if(url.includes('/threads/'))return new Promise(resolve=>pending.push(data=>resolve(response(data))));
    if(url.startsWith('/api/performance/')) {
      if(failScan)throw Error('Provider unavailable');
      const kind=new URL(url,'http://localhost').searchParams.get('kind');
      const data=profileSnapshot(kind);
      if(kind==='cpu')data.summary.cpu_percent=cpu;
      if(delayScan)return new Promise(resolve=>scans.push(data=>resolve(response(data))));
      return response(data);
    }
    throw Error('Unexpected request '+url);
  }});
  const {w,run}=f, get=id=>w.document.getElementById(id), settle=()=>new Promise(r=>setTimeout(r,0));
  run(fs.readFileSync(path.join(root,'frontend/assets/app.js'),'utf8'));
  w.copyFixture=(text)=>copied.push(text);
  run('function toast(){}; async function copy(text){copyFixture(text)}');
  run(fs.readFileSync(path.join(root,'frontend/assets/console-processes.js'),'utf8'));
  run('bindProcessControls()');
  assert.equal(requests.length,0,'Opening Remote Admin must not scan');
  assert(get('refreshProcesses').disabled);
  get('adminPc').value='TESTPC';get('adminPc').dispatchEvent(new w.Event('input'));
  const view=kind=>w.document.querySelector(`[data-performance="${kind}"]`).click();
  view('gpu');view('cpu');view('overview');
  assert.equal(requests.length,0,'Selecting a machine or switching views must not scan');
  assert.equal(get('refreshProcesses').textContent,'Scan Overview');
  await run("admin('overview')");
  assert(requests.includes('/api/performance/TESTPC?kind=overview'));
  assert.equal(get('adminOverview').querySelectorAll('.perf-donut').length,3);
  assert(get('adminOverview').textContent.includes('32 GiB'));
  assert(get('adminOverview').textContent.includes('3 GiB'));
  assert.equal(get('adminOverview').querySelectorAll('.perf-cores > div').length,8);
  assert(get('adminOverview').textContent.includes('Disk responses are elevated'));
  assert.equal(get('adminOut').querySelectorAll('tbody tr').length,snapshot.items.length);
  const first=get('adminOut').querySelector('tbody tr');
  assert(first.textContent.includes('25%'));assert(first.textContent.includes('8 GiB resident'));
  assert(first.querySelector('.perf-meter.perf-high'));assert(first.querySelector('.thread-link.perf-warn'));
  assert(!first.querySelector('.thread-link.perf-high'),'thread count alone must not be red');
  assert.equal(run('perfValue(null,"%")'),'—');assert.equal(run('perfValue(0,"%")'),'0%');
  assert(!run('performanceInsights({cpu_percent:null,memory_percent:null,volumes:[{free_percent:null}]}).length'));
  get('copyPerformance').click();await settle();assert(copied[0].includes('32 GiB'));assert(copied[0].includes('Renderer.exe'));
  // Resource tables, summaries and reports stay scoped to the selected resource.
  await run("admin('cpu')");
  assert.equal(get('adminOverview').querySelectorAll('.perf-donut').length,1);
  assert.equal(get('adminOverview').querySelectorAll('.perf-cores > div').length,8);
  assert(!get('adminOverview').textContent.includes('Disk response'));
  assert.deepEqual([...get('adminOut').querySelectorAll('th')].map(n=>n.textContent),['Process / PID','CPU %','Threads','Actions']);
  get('copyPerformance').click();await settle();
  assert(copied.at(-1).includes('CPU snapshot'));assert(!copied.at(-1).includes('RAM:'));assert(!copied.at(-1).includes('GPU'));
  cpu=91;await run("admin('cpu')");
  assert(get('adminOverview').querySelector('.perf-comparison').textContent.replace(',', '.').includes('+8.6 pp'));
  await run("admin('gpu')");
  assert.equal(get('adminOverview').querySelectorAll('.perf-donut').length,1);
  assert.equal(get('adminOverview').querySelectorAll('.perf-engine').length,3);
  assert.deepEqual([...get('adminOut').querySelectorAll('th')].map(n=>n.textContent),['Process / PID','GPU %','Busiest engine','Actions']);
  assert(!get('adminOut').querySelector('[data-process-threads]'));
  get('copyPerformance').click();await settle();
  assert(copied.at(-1).includes('GPU snapshot'));assert(!copied.at(-1).includes('CPU:'));assert(!copied.at(-1).includes('RAM:'));
  await run("admin('memory')");
  assert.equal(get('adminOverview').querySelectorAll('.perf-donut').length,2);
  assert(get('adminOverview').textContent.includes('Committed memory'));
  assert.deepEqual([...get('adminOut').querySelectorAll('th')].map(n=>n.textContent),['Process / PID','Memory / RAM %','Private commit','Page faults / sec','Handles','Actions']);
  const scanCount=requests.length;
  view('overview');view('gpu');view('memory');view('cpu');
  assert.equal(requests.length,scanCount,'Returning to cached views must not scan');
  assert.equal(get('refreshProcesses').textContent,'Refresh CPU');
  assert(get('adminOverview').textContent.includes('91%'));
  failScan=true;await run("admin('cpu')");failScan=false;
  assert(get('adminOverview').textContent.includes('91%'),'Failed refresh preserves previous sample');
  assert(get('processStatus').textContent.includes('Showing the previous scan'));
  // Switching while a manual scan completes must not render into the wrong view.
  delayScan=true;const scanning=run("admin('cpu')");
  assert(get('refreshProcesses').disabled);assert(get('diagnoseSlowness').disabled);
  view('gpu');await run("admin('memory')");
  assert.equal(scans.length,1,'No overlapping manual scans');
  scans[0](profileSnapshot('cpu'));await scanning;delayScan=false;
  assert.equal(get('performanceTitle').textContent,'GPU activity');
  assert(!get('adminOut').textContent.includes('CPU %'));
  assert(!get('refreshProcesses').disabled);
  view('overview');
  const opening=run('showProcessThreads(0)');await settle();
  assert(get('threadDialog').open);assert(get('refreshThreads').disabled);
  const url=new URL(requests.at(-1),'http://localhost');
  assert(url.pathname.endsWith('/threads/42'));assert.equal(url.searchParams.get('created'),snapshot.items[0].CreatedAt);
  pending[0](threads);await opening;
  assert(!get('refreshThreads').disabled);assert(get('threadBody').textContent.includes('96%'));assert(get('threadBody').textContent.includes('12%'));
  assert(get('threadBody').textContent.includes('User request'));
  const stale=run('refreshProcessThreads()');await settle();
  get('adminPc').value='OTHERPC';get('adminPc').dispatchEvent(new w.Event('input'));
  pending[1]({...threads,items:[{...threads.items[0],TID:999999}]});await stale;
  assert(!get('threadDialog').open);assert(!get('threadBody').textContent.includes('999999'));assert.equal(get('adminOut').textContent,'');
  // Partial providers retain unknowns and escape server-supplied text.
  get('adminPc').value='TESTPC';await run("admin('memory')");
  run('processSnapshot=Object.freeze({...processSnapshot,data:{...processSnapshot.data,summary:{},warnings:["<img src=x onerror=bad()>"]}});renderPerformance()');
  assert.equal(get('adminOverview').querySelectorAll('.perf-donut b').length,2);
  assert([...get('adminOverview').querySelectorAll('.perf-donut b')].every(node=>node.textContent==='—'));
  assert(!get('adminOverview').querySelector('img'));assert(get('adminOverview').textContent.includes('partial results shown'));
  await run("admin('gpu')");
  run('processSnapshot=Object.freeze({...processSnapshot,data:{...processSnapshot.data,summary:{},warnings:["GPU unavailable"]}});renderPerformance()');
  assert(get('adminOverview').textContent.includes('Unavailable does not mean 0%'));
  assert.equal(get('adminOverview').querySelector('.perf-donut b').textContent,'—');
  get('adminPc').value='NEWPC';get('adminPc').dispatchEvent(new w.Event('input'));
  const beforeSwitch=requests.length;view('cpu');view('memory');view('overview');
  assert.equal(get('adminOut').textContent,'');assert(get('copyPerformance').disabled);
  assert.equal(requests.length,beforeSwitch,'Machine changes clear all cached scans without requesting new ones');
  assert.equal(f.errors.length,0,f.errors.join('\n'));w.close();
  console.log('PASS: performance gauges, readable RAM, thresholds, thread drill-down, guarded refresh, partial data, safe rendering and report copy');
})().catch(e=>{console.error(e);process.exitCode=1});
