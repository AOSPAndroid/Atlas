const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {fixture, root} = require('./ui_fixture.cjs');
const settle = () => new Promise(resolve => setTimeout(resolve, 0));
const record = (name, changes = {}) => ({name, display_name: `Display ${name}`, state: 'Running', start_mode: 'Auto', pid: 1234, can_stop: true, stop_reason: '', identity: 'a'.repeat(64), ...changes});
(async () => {
  const requests = [];
  const f = await fixture(), {w, run} = f, get = id => w.document.getElementById(id);
  w.AtlasClient.request = (url, options) => new Promise((resolve, reject) => requests.push({url, payload: JSON.parse(options.body), resolve, reject}));
  run(fs.readFileSync(path.join(root, 'frontend/assets/remote-services.js'), 'utf8'));
  await settle();
  assert(get('adminServices').disabled); assert.equal(requests.length, 0);
  get('adminPc').value = 'testpc'; get('adminPc').dispatchEvent(new w.Event('input'));
  assert(!get('adminServices').disabled); assert.equal(requests.length, 0, 'Selecting a target does not query services');
  get('adminServices').click(); get('adminServices').click();
  assert(get('servicesDialog').open); assert(get('refreshServices').disabled);
  assert.equal(requests.length, 1); assert.equal(requests[0].url, '/api/services');
  assert.deepEqual(requests[0].payload, {computer: 'TESTPC'});
  requests[0].resolve({computer: 'TESTPC', items: [record('A180'), record('OpenFin'), record('RpcSs', {can_stop: false, stop_reason: 'Required for Windows'}), record('<img src=x onerror=bad()>')]}); await settle();
  assert.equal(get('servicesCount').textContent, '4 of 4 services');
  assert.equal(get('servicesBody').querySelectorAll('img').length, 0, 'Service metadata is rendered as text');
  assert(get('servicesBody').querySelector('[data-service-stop="2"]').disabled);
  get('servicesFilter').value = 'a180'; get('servicesFilter').dispatchEvent(new w.Event('input'));
  assert.equal(get('servicesCount').textContent, '1 of 4 services');
  const stopButton = () => get('servicesBody').querySelector('[data-service-stop="0"]');
  stopButton().click();
  assert(get('serviceStopDialog').open); assert(get('serviceStopQuestion').textContent.includes('A180') && get('serviceStopQuestion').textContent.includes('TESTPC'));
  assert.equal(w.document.activeElement.id, 'cancelServiceStop');
  assert.equal(requests.length, 1, 'Stop requires confirmation');
  get('cancelServiceStop').click(); await settle(); assert.equal(requests.length, 1);
  stopButton().click(); get('confirmServiceStop').click(); get('confirmServiceStop').click(); await settle();
  assert.equal(requests.length, 2); assert.equal(requests[1].url, '/api/services/stop');
  assert.deepEqual(requests[1].payload, {computer: 'TESTPC', name: 'A180', expected_identity: 'a'.repeat(64)});
  assert(get('refreshServices').disabled && stopButton().disabled);
  requests[1].resolve({computer: 'TESTPC', name: 'A180', outcome: 'stopped', state: 'Stopped', message: 'Service stopped.'}); await settle();
  assert(get('servicesStatus').textContent.includes('Service stopped.'));
  assert(get('servicesBody').textContent.includes('Stopped')); assert(stopButton().disabled);
  get('servicesFilter').value = 'openfin'; get('servicesFilter').dispatchEvent(new w.Event('input'));
  get('servicesBody').querySelector('button').click(); get('confirmServiceStop').click(); await settle();
  requests[2].resolve({computer: 'TESTPC', name: 'OpenFin', outcome: 'pending', state: 'Stop Pending', message: 'Stopped was not verified.'}); await settle();
  assert(get('servicesStatus').textContent.includes('not verified')); assert(get('servicesStatus').textContent.includes('Refresh'));
  assert(get('servicesBody').querySelector('button').disabled); assert.equal(requests.length, 3, 'Pending stop is never retried automatically');
  get('refreshServices').click();
  get('adminPc').value = 'PC2'; get('adminPc').dispatchEvent(new w.Event('input'));
  requests[3].resolve({computer: 'TESTPC', items: [record('OldService')]}); await settle();
  assert(!get('servicesBody').textContent.includes('OldService'), 'A stale response cannot populate a different target');
  assert.equal(get('servicesTarget').textContent, 'PC2');
  get('servicesFilter').value = ''; get('servicesFilter').dispatchEvent(new w.Event('input'));
  get('refreshServices').click(); requests[4].resolve({computer: 'PC2', items: [record('TestService')]}); await settle();
  stopButton().click(); get('adminPc').value = 'PC3'; w.dispatchEvent(new w.Event('atlas:admin-target-change')); await settle();
  assert(!get('serviceStopDialog').open); assert.equal(requests.length, 5, 'Changing target cancels confirmation including programmatic selection');
  get('refreshServices').click(); requests[5].resolve({computer: 'PC3', items: [record('TestService')]}); await settle();
  stopButton().click(); get('confirmServiceStop').click(); await settle();
  get('adminPc').value = 'PC4'; get('adminPc').dispatchEvent(new w.Event('input'));
  requests[6].resolve({computer: 'PC3', name: 'TestService', outcome: 'stopped', state: 'Stopped', message: 'Old target stopped.'}); await settle();
  assert(!get('servicesStatus').textContent.includes('Old target'));
  get('refreshServices').click(); requests[7].resolve({computer: 'PC4', items: [record('TestService')]}); await settle();
  stopButton().click(); get('confirmServiceStop').click(); await settle();
  requests[8].reject(Error('Access denied')); await settle();
  assert(get('servicesStatus').textContent.includes('Access denied')); assert(stopButton().disabled);
  get('refreshServices').click(); requests[9].resolve({computer: 'WRONGPC', items: [record('WrongService')]}); await settle();
  assert(!get('servicesBody').textContent.includes('WrongService')); assert(get('servicesStatus').textContent.includes('did not match'));
  get('refreshServices').click(); get('closeServices').click();
  requests[10].resolve({computer: 'PC4', items: [record('ClosedResponse')]}); await settle();
  assert(!get('servicesDialog').open); assert(!get('servicesBody').textContent.includes('ClosedResponse'));
  w.AtlasReadOnly = {reason: 'Read-only'};
  get('adminServices').disabled = false; get('adminServices').click();
  get('refreshServices').disabled = false; get('refreshServices').click(); await settle();
  assert.equal(requests.length, 11, 'Read-only guards protect listing and stopping even with forced button activation');
  assert.equal(f.errors.length, 0, f.errors.join('\n'));
  w.close(); console.log('PASS: service inventory/search, safe text, confirmed exact service stop, pending/error state, duplicate/stale target prevention, close and read-only guards.');
})().catch(error => {console.error(error); process.exitCode = 1});
